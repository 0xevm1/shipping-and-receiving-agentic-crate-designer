import { ORIENTATIONS, rotatedSize, type Orientation } from "./orientations";
import type { Vec3 } from "./schema";
import { DEFAULT_STANDARDS, type ShopStandards } from "./standards";

/**
 * Grid packing of N identical parts, using each part's bounding box.
 *
 * Crates never mix parts, so every slot is the same size: the problem reduces to
 * choosing an orientation and an nx × ny × nz grid. We enumerate every
 * combination and rank them. This is exact for bounding boxes and fast enough
 * to re-run on every keystroke (6 orientations × a few hundred grids).
 */

export interface PackingInput {
  partSize: Vec3;
  quantity: number;
  keepUpright: boolean;
  maxLayers: number;
  partGapMm: number;
  wallClearanceMm: number;
  /** Thickness of the plywood sheet placed between stacked layers. */
  separatorMm: number;
  /**
   * Amount the crate structure adds to the interior on each axis (walls, cleats, skids, lid).
   * A function sizes it per layout from the interior and grid (#7: the base is sized for its spans).
   */
  structureAllowance: Vec3 | ((grid: Pick<Layout, "interior" | "cellSize" | "counts" | "clearance">) => Vec3);
  /**
   * Smallest interior on any axis. A tiny part's crate is padded up to this, with
   * the extra split evenly as clearance, so the cleat frame still fits.
   */
  minInteriorMm: number;
}

export interface Slot {
  /** Grid index [i, j, k]. */
  index: [number, number, number];
  /** Min corner of the part's rotated bounding box, in crate-interior coordinates. */
  min: Vec3;
}

export interface Layout {
  key: string;
  orientation: Orientation;
  /** Rotated part bounding box. */
  cellSize: Vec3;
  counts: [number, number, number];
  interior: Vec3;
  /**
   * Clearance to the walls, floor and lid on each axis. Equals the wall
   * clearance setting unless the interior was padded up to its minimum.
   */
  clearance: Vec3;
  external: Vec3;
  externalVolumeM3: number;
  /** Fraction of interior volume occupied by part bounding boxes. */
  utilization: number;
  /** External height at most `limits.stableHeightRatio` (1.5) × the narrowest base side (low tip-over risk). */
  stable: boolean;
  /** Filled slots, bottom layer first. */
  slots: Slot[];
}

export function enumerateLayouts(input: PackingInput, standards: ShopStandards = DEFAULT_STANDARDS): Layout[] {
  const ratio = standards.limits.stableHeightRatio;
  const { quantity: n, partGapMm: gap, wallClearanceMm: clear, separatorMm: sep } = input;
  const orientations = ORIENTATIONS.filter((o) => !input.keepUpright || o.upright);
  const seen = new Set<string>();
  const layouts: Layout[] = [];

  for (const orientation of orientations) {
    const [a, b, c] = rotatedSize(input.partSize, orientation);

    for (let nz = 1; nz <= Math.min(input.maxLayers, n); nz++) {
      const perLayer = Math.ceil(n / nz);
      if (perLayer * (nz - 1) >= n) continue; // top layer would be empty

      for (let nx = 1; nx <= perLayer; nx++) {
        const ny = Math.ceil(perLayer / nx);
        if ((nx - 1) * ny >= perLayer) continue; // a whole column would be empty

        const content: Vec3 = [nx * a + (nx - 1) * gap, ny * b + (ny - 1) * gap, nz * c + (nz - 1) * (gap + sep)];
        const clearance = content.map((v) => Math.max(clear, (input.minInteriorMm - v) / 2)) as Vec3;
        const interior: Vec3 = [
          2 * clearance[0] + nx * a + (nx - 1) * gap,
          2 * clearance[1] + ny * b + (ny - 1) * gap,
          2 * clearance[2] + nz * c + (nz - 1) * (gap + sep),
        ];
        // Treat X as the crate's long axis (skids run along X); the rotated
        // twin of each layout is generated by the "turned" orientation.
        if (interior[0] < interior[1]) continue;

        const key = `${orientation.upright ? "u" : "s"}:${interior.map(Math.round).join("x")}:${nx}${ny}${nz}`;
        const dedupeKey = key.slice(2);
        if (seen.has(dedupeKey)) continue;
        seen.add(dedupeKey);

        const counts: [number, number, number] = [nx, ny, nz];
        const allowance =
          typeof input.structureAllowance === "function"
            ? input.structureAllowance({ interior, cellSize: [a, b, c], counts, clearance })
            : input.structureAllowance;
        const external: Vec3 = [interior[0] + allowance[0], interior[1] + allowance[1], interior[2] + allowance[2]];

        const slots: Slot[] = [];
        outer: for (let k = 0; k < nz; k++) {
          for (let j = 0; j < ny; j++) {
            for (let i = 0; i < nx; i++) {
              if (slots.length === n) break outer;
              slots.push({
                index: [i, j, k],
                min: [clearance[0] + i * (a + gap), clearance[1] + j * (b + gap), clearance[2] + k * (c + gap + sep)],
              });
            }
          }
        }

        layouts.push({
          key,
          orientation,
          cellSize: [a, b, c],
          counts,
          interior,
          clearance,
          external,
          externalVolumeM3: (external[0] * external[1] * external[2]) / 1e9,
          utilization: (n * a * b * c) / (interior[0] * interior[1] * interior[2]),
          stable: external[2] <= ratio * Math.min(external[0], external[1]),
          slots,
        });
      }
    }
  }

  const tolerance = standards.defaults.volumeTolerance;
  return layouts.sort((x, y) => compareLayouts(x, y, tolerance));
}

/**
 * Stable crates first, then smallest external volume, then lowest height. Volumes within
 * `tolerance` (`defaults.volumeTolerance`, 3%) count as equal, so the lower crate wins.
 */
export function compareLayouts(x: Layout, y: Layout, tolerance = DEFAULT_STANDARDS.defaults.volumeTolerance): number {
  if (x.stable !== y.stable) return x.stable ? -1 : 1;
  const dv = x.externalVolumeM3 - y.externalVolumeM3;
  if (Math.abs(dv) > tolerance * Math.min(x.externalVolumeM3, y.externalVolumeM3)) return dv;
  return x.external[2] - y.external[2];
}
