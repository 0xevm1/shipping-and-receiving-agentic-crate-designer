import { ORIENTATIONS, rotatedSize, type Orientation } from "./orientations";
import type { Vec3 } from "./schema";

/**
 * Grid packing of N identical parts, using each part's bounding box.
 *
 * Crates never mix parts, so every slot is the same size: the problem reduces to
 * choosing an orientation and an nx × ny × nz grid. We enumerate every
 * combination and rank them. This is exact for bounding boxes and fast enough
 * to re-run on every keystroke (6 orientations × a few hundred grids).
 */

export interface PackingInput {
  partSize: Vec3;
  quantity: number;
  keepUpright: boolean;
  maxLayers: number;
  partGapMm: number;
  wallClearanceMm: number;
  /** Thickness of the plywood sheet placed between stacked layers. */
  separatorMm: number;
  /** Amount the crate structure adds to the interior on each axis (walls, cleats, skids, lid). */
  structureAllowance: Vec3;
}

export interface Slot {
  /** Grid index [i, j, k]. */
  index: [number, number, number];
  /** Min corner of the part's rotated bounding box, in crate-interior coordinates. */
  min: Vec3;
}

export interface Layout {
  key: string;
  orientation: Orientation;
  /** Rotated part bounding box. */
  cellSize: Vec3;
  counts: [number, number, number];
  interior: Vec3;
  external: Vec3;
  externalVolumeM3: number;
  /** Fraction of interior volume occupied by part bounding boxes. */
  utilization: number;
  /** External height no greater than the narrowest base side (low tip-over risk). */
  stable: boolean;
  /** Filled slots, bottom layer first. */
  slots: Slot[];
}

export function enumerateLayouts(input: PackingInput): Layout[] {
  const { quantity: n, partGapMm: gap, wallClearanceMm: clear, separatorMm: sep } = input;
  const orientations = ORIENTATIONS.filter((o) => !input.keepUpright || o.upright);
  const seen = new Set<string>();
  const layouts: Layout[] = [];

  for (const orientation of orientations) {
    const [a, b, c] = rotatedSize(input.partSize, orientation);

    for (let nz = 1; nz <= Math.min(input.maxLayers, n); nz++) {
      const perLayer = Math.ceil(n / nz);
      if (perLayer * (nz - 1) >= n) continue; // top layer would be empty

      for (let nx = 1; nx <= perLayer; nx++) {
        const ny = Math.ceil(perLayer / nx);
        if ((nx - 1) * ny >= perLayer) continue; // a whole column would be empty

        const interior: Vec3 = [
          2 * clear + nx * a + (nx - 1) * gap,
          2 * clear + ny * b + (ny - 1) * gap,
          2 * clear + nz * c + (nz - 1) * (gap + sep),
        ];
        // Treat X as the crate's long axis (skids run along X); the rotated
        // twin of each layout is generated by the "turned" orientation.
        if (interior[0] < interior[1]) continue;

        const key = `${orientation.upright ? "u" : "s"}:${interior.map(Math.round).join("x")}:${nx}${ny}${nz}`;
        const dedupeKey = key.slice(2);
        if (seen.has(dedupeKey)) continue;
        seen.add(dedupeKey);

        const external: Vec3 = [
          interior[0] + input.structureAllowance[0],
          interior[1] + input.structureAllowance[1],
          interior[2] + input.structureAllowance[2],
        ];

        const slots: Slot[] = [];
        outer: for (let k = 0; k < nz; k++) {
          for (let j = 0; j < ny; j++) {
            for (let i = 0; i < nx; i++) {
              if (slots.length === n) break outer;
              slots.push({
                index: [i, j, k],
                min: [clear + i * (a + gap), clear + j * (b + gap), clear + k * (c + gap + sep)],
              });
            }
          }
        }

        layouts.push({
          key,
          orientation,
          cellSize: [a, b, c],
          counts: [nx, ny, nz],
          interior,
          external,
          externalVolumeM3: (external[0] * external[1] * external[2]) / 1e9,
          utilization: (n * a * b * c) / (interior[0] * interior[1] * interior[2]),
          stable: external[2] <= Math.min(external[0], external[1]),
          slots,
        });
      }
    }
  }

  return layouts.sort(compareLayouts);
}

/** Stable crates first, then smallest external volume, then lowest height. */
export function compareLayouts(x: Layout, y: Layout): number {
  if (x.stable !== y.stable) return x.stable ? -1 : 1;
  const dv = x.externalVolumeM3 - y.externalVolumeM3;
  if (Math.abs(dv) > 1e-6) return dv;
  return x.external[2] - y.external[2];
}
